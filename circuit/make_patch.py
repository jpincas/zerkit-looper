"""Write src/firmware-patch.js: LOOP06 as edits to Novation's official 1.2.1 image, so the
browser can build it from the user's own copy of the official file (we can't ship Novation's).

    .venv/bin/python make_patch.py incoming/circuittracks-firmware-4486.syx

The edits hold only our bytes: the branches into our code at the patched call sites, the
version mark, and the code and splash table appended after the stock image (with its 0xFF
padding). Each run is checked against the stock image to contain no stock byte unchanged.
"""
import json
import os
import sys
import fw
import build_lights as BL

stock = fw.load_stock(sys.argv[1])
img, *_ = BL.build(stock, splash=True)
syx = fw.encode(img)
image = fw.decode(syx)                       # what's sent: padded to 32-byte blocks

edits, i = [], 0
while i < len(image):
    if i >= len(stock) or image[i] != stock[i]:
        j = i
        while j < len(image) and (j >= len(stock) or image[j] != stock[j]):
            j += 1
        edits.append([i, image[i:j].hex()])
        i = j
    else:
        i += 1

out = os.path.join(os.path.dirname(__file__), '..', 'src', 'firmware-patch.js')
with open(out, 'w') as f:
    f.write('// LOOP06 as edits to the official Circuit Tracks 1.2.1 image. Generated by circuit/make_patch.py.\n')
    f.write('export default {\n')
    f.write(f"  mark: 'LOOP06',\n  stockSyx: '{fw.STOCK_SYX_SHA}',\n  stockImage: '{fw.STOCK_IMG_SHA}',\n")
    f.write(f"  size: {len(image)},\n  sha: '{fw.sha256(syx)}',\n  edits: [   // [offset, hex bytes]\n")
    for off, h in edits:
        f.write(f'    [{off:#x}, {json.dumps(h)}],\n')
    f.write('  ],\n};\n')
print(f'{len(edits)} edits, {sum(len(h) // 2 for _, h in edits)} bytes; LOOP06 sha256 {fw.sha256(syx)}')
